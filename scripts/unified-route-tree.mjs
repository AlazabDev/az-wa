#!/usr/bin/env node
// AzWA: canonical inventory/guard for TanStack Start routes. Does not modify routeTree.gen.ts.
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join, relative, resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const routes = join(root, 'src/routes');
const generated = join(root, 'src/routeTree.gen.ts');
const document = join(root, 'docs/ROUTE_TREE.md');
const mode = process.argv[2] || '--check';
if (!['--check', '--write'].includes(mode)) throw new Error('Use --check or --write');

function list(dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) return list(path);
    return entry.isFile() && /\.(?:ts|tsx)$/.test(entry.name) && !/\.(?:test|spec)\.(?:ts|tsx)$/.test(entry.name) ? [path] : [];
  });
}
function assert(condition, message) { if (!condition) throw Error(message); }
function urlForId(id) {
  if (id === '/') return '/';
  let s = id.replace(/\/_authenticated(?=\/|$)/g, '');
  s = s.replace(/\/\$(\w+)/g, '/:$1').replace(/\/$/, '') || '/';
  return s;
}
const files = list(routes);
const seenIds = new Map();
const seenPaths = new Map();
const entries = files.map((path) => {
  const file = relative(routes, path).replaceAll('\\', '/');
  const text = readFileSync(path, 'utf8');
  const id = file === '__root.tsx' || file === '__root.ts'
    ? '__root'
    : text.match(/export\s+const\s+Route\s*=\s*createFileRoute\s*\(\s*['"]([^'"]+)['"]\s*\)/)?.[1];
  assert(id, `Missing literal TanStack route declaration: ${file}`);
  assert(!seenIds.has(id), `Duplicate route ID ${id}: ${file} and ${seenIds.get(id)}`);
  seenIds.set(id, file);
  const kind = id === '__root' ? 'root' : id === '/_authenticated' ? 'layout' : id.startsWith('/api/') ? 'api' : 'page';
  const url = kind === 'root' || kind === 'layout' ? '—' : urlForId(id);
  if (url !== '—') {
    assert(!seenPaths.has(url), `Duplicate URL ${url}: ${file} and ${seenPaths.get(url)}`);
    seenPaths.set(url, file);
  }
  return { file, id, url, kind };
}).sort((a, b) => a.id.localeCompare(b.id));
assert(existsSync(generated), 'Missing generated TanStack route tree');
const imports = [...readFileSync(generated, 'utf8').matchAll(/from ['"]\.\/routes\/([^'"]+)['"]/g)].map(x => x[1]);
const source = entries.map(e => e.file.replace(/\.(?:ts|tsx)$/, '')).sort();
assert(JSON.stringify([...imports].sort()) === JSON.stringify(source), 'routeTree.gen.ts does not match src/routes (run build to regenerate)');
const activeEntry = readFileSync(join(root, 'src/router.tsx'), 'utf8');
assert(activeEntry.includes('"./routeTree.gen"'), 'src/router.tsx must use canonical generated TanStack tree');
assert(!/react-router-dom|\.\/App(?:\.|['"])/.test(activeEntry), 'Canonical router must not load React Router SPA');
// Only the canonical routes are executable. Legacy Next.js routes and the old SPA remain untouched.
for (const e of entries) {
  const body = readFileSync(join(routes, e.file), 'utf8');
  assert(!/from\s*['"](?:@\/app\/|@\/pages\/|\.\.\/app\/|\.\.\/pages\/)/.test(body), `TanStack route imports legacy route module: ${e.file}`);
}
const header = [
 '# AzWA — Unified Route Tree',
 '',
 '> Generated by `node scripts/unified-route-tree.mjs --write`. Do not edit routeTree.gen.ts manually.',
 '> Only `src/routes/**` is active for TanStack Start. `src/app/**` (Next.js) and `src/App.tsx` + `src/pages/**` (React Router SPA) are retained as legacy references, not merged into the live router.',
 '',
 `Total: **${entries.length}** route modules; **${entries.filter(e => e.kind === 'page').length}** page modules; **${entries.filter(e => e.kind === 'api').length}** API modules; **1** root; **1** layout.`,
 '',
 '| Type | URL | Route ID | Source |',
 '|---|---|---|---|',
 ...entries.map(e => `| ${e.kind} | \`${e.url}\` | \`${e.id}\` | \`src/routes/${e.file}\` |`),
 '',
 '## Implementation rules',
 '',
 '1. Add or modify pages/API handlers only in `src/routes/` using `createFileRoute`.',
 '2. Never import `src/app` Next.js route handlers or `src/pages` React Router pages directly into active route modules.',
 '3. Reuse business logic by extracting it into `src/lib/`, `src/services/`, or `src/components/` rather than copying route handlers.',
 '4. `src/routeTree.gen.ts` is generated; run the Vite build and check the inventory again.',
 '5. The inventory test confirms source/tree consistency, not runtime health or API endpoint integration.',
 '',
].join('\n');
if (mode === '--write') {
  writeFileSync(document, header);
  console.log(`Wrote ${relative(root, document)} (${entries.length} routes)`);
} else {
  assert(existsSync(document), 'Missing docs/ROUTE_TREE.md; run --write');
  assert(readFileSync(document, 'utf8') === header, 'Route inventory outdated; run --write and commit the result');
  console.log(`PASS: unified TanStack tree; ${entries.length} route modules; no duplicate IDs/URLs or legacy route imports`);
}

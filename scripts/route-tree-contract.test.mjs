import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync, readdirSync, existsSync } from 'node:fs';
import { resolve, relative, join, extname } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const routesRoot = resolve(root, 'src/routes');
const generatedPath = resolve(root, 'src/routeTree.gen.ts');

function allRoutes(dir) {
  const files = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) files.push(...allRoutes(full));
    else if (entry.isFile() && ['.ts', '.tsx'].includes(extname(entry.name)) && !entry.name.endsWith('.test.ts')) {
      files.push(relative(routesRoot, full).replace(/\.(tsx|ts)$/, '').split('\\').join('/'));
    }
  }
  return files;
}

test('generated TanStack route tree references exactly all current route files', () => {
  assert.ok(existsSync(generatedPath), 'src/routeTree.gen.ts missing');
  const tree = readFileSync(generatedPath, 'utf8');
  assert.match(tree, /automatically generated by TanStack Router/);
  const imports = [...tree.matchAll(/from ['"]\.\/routes\/([^'"]+)['"]/g)].map(x => x[1]);
  assert.equal(new Set(imports).size, imports.length, 'duplicate generated route imports');
  const sourceRoutes = allRoutes(routesRoot);
  assert.deepEqual([...new Set(imports)].sort(), [...sourceRoutes].sort(), 'route tree is stale, missing routes or contains deleted routes');
});

test('each route module declares a TanStack route and correct file route identifier', () => {
  for (const file of allRoutes(routesRoot)) {
    const body = readFileSync(resolve(routesRoot, `${file}${existsSync(resolve(routesRoot, `${file}.tsx`)) ? '.tsx' : '.ts'}`), 'utf8');
    if (file === '__root') {
      assert.match(body, /createRootRoute/);
    } else {
      assert.match(body, /createFileRoute\s*\(/, `${file}: no createFileRoute`);
      // The literal identifier must match the filesystem path. Pathless layouts preserve their underscore segments.
      const expected = (file === 'index' ? '' : file.replace(/\/route$/, '').replace(/\/index$/, '/')).replaceAll('.', '/');
      const match = body.match(/createFileRoute\s*\(\s*['"]([^'"]+)['"]/);
      assert.ok(match, `${file}: missing literal route ID`);
      assert.equal(match[1], `/${expected}`.replace(/\/\//g, '/'), `${file}: route ID mismatch`);
    }
  }
});
